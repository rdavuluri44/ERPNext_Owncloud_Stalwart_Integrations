#!/usr/bin/env python3
"""Open-source projects we use, borrow from or evaluate: one list, credited and tracked in step (P35).

Working agreements (owner, 26 November 2026): every open-source project we use is credited and its repository is
tracked; a project is added to `docs/open-source.json` when it is evaluated, and credited and tracked in the same
pull request that adopts it or copies its code.

    python3 tools/open_source.py check    # the list agrees with the upstream watch, modules.json and the README
    python3 tools/open_source.py render   # write the README acknowledgements and docs/open-source.md

Statuses: adopted (runs in or builds our system), borrowed (code copied into this repository), evaluating
(chosen or under review, not in the code yet), retired (used before). Adopted and borrowed projects are credited in
the README and are either watched daily (`watch`: keys of `deployment/upstream-watch.json`) or say why not
(`not_watched`). Every component the upstream watch follows and every upstream named in `modules.json` must be in
the list, so the credits and the tracking cannot drift apart.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIST = ROOT / 'docs' / 'open-source.json'
PAGE = ROOT / 'docs' / 'open-source.md'
README = ROOT / 'README.md'
WATCH = ROOT / 'deployment' / 'upstream-watch.json'
MODULES = ROOT / 'modules.json'
START, END = '<!-- OPEN-SOURCE:START (generated by tools/open_source.py) -->', '<!-- OPEN-SOURCE:END -->'
STATUSES = ('adopted', 'borrowed', 'evaluating', 'retired')
CREDITED = ('adopted', 'borrowed')


def url_key(url):
    url = (url or '').strip().lower().rstrip('/')
    url = re.sub(r'\.git$', '', url)
    return re.sub(r'^https?://(www\.)?', '', url)


def load_json(path):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def module_upstreams(modules):
    mods = modules['modules'] if isinstance(modules, dict) and 'modules' in modules else modules
    return [(m['id'], u.get('name'), u.get('url')) for m in mods for u in m.get('upstream', [])]


def validate(ledger, watch, modules):
    errors, names = [], set()
    known_urls = {}
    watched = {}
    for p in ledger.get('projects', []):
        name = p.get('name') or '?'
        if name in names:
            errors.append(name + ': listed twice')
        names.add(name)
        status = p.get('status')
        if status not in STATUSES:
            errors.append(name + ': status must be one of ' + ', '.join(STATUSES))
        if not p.get('licence'):
            errors.append(name + ': licence missing (write "to verify" when unknown)')
        if not p.get('used_in'):
            errors.append(name + ': used_in missing (module or P item)')
        if not p.get('repo') and status != 'evaluating':
            errors.append(name + ': repository missing')
        if status in CREDITED and not (p.get('watch') or p.get('not_watched')):
            errors.append(name + ': adopted or borrowed, but neither watched nor a reason why not')
        if status == 'evaluating' and not p.get('note'):
            errors.append(name + ': say what is being evaluated and for which item')
        for key in p.get('watch', []):
            if key not in watch.get('sources', {}):
                errors.append(name + ': watch key ' + key + ' is not in deployment/upstream-watch.json')
            watched.setdefault(key, []).append(name)
        for url in [p.get('repo')] + p.get('also', []):
            if url:
                known_urls[url_key(url)] = name
    for key in watch.get('sources', {}):
        if key not in watched:
            errors.append('the upstream watch follows ' + key + ', but the open-source list does not credit it')
        elif len(watched[key]) > 1:
            errors.append('watch key ' + key + ' is claimed by ' + ', '.join(watched[key]))
    for module, name, url in module_upstreams(modules):
        if url and url_key(url) not in known_urls:
            errors.append(f'modules.json ({module}) names {name} ({url}), which is not in the open-source list')
    return errors


def readme_section(ledger):
    credited = [p for p in ledger['projects'] if p['status'] in CREDITED]
    retired = [p for p in ledger['projects'] if p['status'] == 'retired']
    names = [p.get('credit') or p['name'] for p in credited]
    text = ('This small-office system is built on open-source projects, used, integrated or configured here: '
            + ', '.join(names[:-1]) + ' and ' + names[-1] + '.')
    if retired:
        text += ' Used before: ' + ', '.join(p['name'] + (' (' + p['note'] + ')' if p.get('note') else '') for p in retired) + '.'
    text += (' Thank you to their communities. Each remains under its own licence; the full list with licences,'
             ' where each is used, how we track it and what we are evaluating is in'
             ' [docs/open-source.md](docs/open-source.md) (see also LICENSES.md).')
    lines, line = [], ''
    for word in text.split(' '):
        if len(line) + len(word) + 1 > 110:
            lines.append(line)
            line = word
        else:
            line = (line + ' ' + word).strip()
    lines.append(line)
    return '\n'.join([START] + lines + [END])


def page(ledger):
    out = ['# Open-source projects', '',
           '> Generated from `docs/open-source.json` by `tools/open_source.py render`; edit the JSON. Every project we',
           '> use, borrow code from or evaluate, with its licence, where we use it and how we track it (P35). Licences',
           '> as read from each repository on the date of the entry; "to verify" where the repository states none.', '']
    titles = {'adopted': 'In use', 'borrowed': 'Code borrowed into this repository', 'evaluating':
              'Being evaluated or chosen, not in the code yet', 'retired': 'Used before'}
    for status in STATUSES:
        rows = [p for p in ledger['projects'] if p['status'] == status]
        if not rows:
            continue
        out += ['## ' + titles[status], '', '| Project | Licence | Used in | Tracked | Note |', '|---|---|---|---|---|']
        for p in rows:
            link = f"[{p['name']}]({p['repo']})" if p.get('repo') else p['name']
            tracked = ('daily watch: ' + ', '.join('`' + k + '`' for k in p['watch'])) if p.get('watch') else (
                p.get('not_watched') or '—')
            out.append(f"| {link} | {p['licence']} | {', '.join(p['used_in'])} | {tracked} | {p.get('note', '')} |")
        out.append('')
    return '\n'.join(out).rstrip() + '\n'


def readme_with(text, section):
    if START not in text or END not in text:
        raise ValueError('README.md has no generated open-source section markers')
    head, rest = text.split(START, 1)
    return head + section + rest.split(END, 1)[1]


def main(argv=None):
    parser = argparse.ArgumentParser(description='Open-source list: credits and tracking in step (P35).')
    parser.add_argument('command', choices=('check', 'render'))
    args = parser.parse_args(argv)
    ledger, watch, modules = load_json(LIST), load_json(WATCH), load_json(MODULES)
    errors = validate(ledger, watch, modules)
    if errors:
        print('the open-source list is not in step:\n  ' + '\n  '.join(errors))
        return 1
    readme = README.read_text(encoding='utf-8')
    if args.command == 'render':
        README.write_text(readme_with(readme, readme_section(ledger)), encoding='utf-8', newline='\n')
        PAGE.write_text(page(ledger), encoding='utf-8', newline='\n')
        print('wrote README.md (acknowledgements) and docs/open-source.md')
        return 0
    stale = [str(p.relative_to(ROOT)) for p, want in ((README, readme_with(readme, readme_section(ledger))),
                                                      (PAGE, page(ledger)))
             if not p.is_file() or p.read_text(encoding='utf-8') != want]
    if stale:
        print('out of date, run: python3 tools/open_source.py render (' + ', '.join(stale) + ')')
        return 1
    counts = {s: sum(1 for p in ledger['projects'] if p['status'] == s) for s in STATUSES}
    print('open-source list in step: ' + ', '.join(f'{n} {s}' for s, n in counts.items()))
    return 0


if __name__ == '__main__':
    sys.exit(main())
